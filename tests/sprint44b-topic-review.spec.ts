import { expect, test } from "@playwright/test";
import { reviewPeriod, scheduleTopicReview } from "../src/features/learning/TopicReview";
import { createRealStudy } from "./helpers/real-study";
import { readIndexedDBStore } from "./helpers/indexed-db";

test("calendário local, revisão antecipada, erros e dificuldade declarada", () => {
  const topic = { discipline: "A", studyId: "study-a", topic: "Vetores" };
  const now = new Date(2026, 10, 11, 15, 30);
  const first = scheduleTopicReview(topic, undefined, "correct", "normal", now);
  expect(first.nextReviewAt).toBe(new Date(2026, 10, 12, 15, 30).toISOString());
  expect(reviewPeriod(first.nextReviewAt, now)).toBe("upcoming");
  expect(reviewPeriod(first.nextReviewAt, new Date(2026, 10, 12))).toBe("today");
  expect(reviewPeriod(first.nextReviewAt, new Date(2026, 10, 13))).toBe("late");
  const early = scheduleTopicReview(topic, first, "correct", "normal", now);
  expect(early.nextReviewAt).toBe(new Date(2026, 10, 14, 15, 30).toISOString());
  const hard = scheduleTopicReview(topic, early, "correct", "hard", now);
  expect(hard.nextReviewAt).toBe(early.nextReviewAt);
  const wrong = scheduleTopicReview(topic, hard, "wrong", "normal", now);
  expect(wrong.nextReviewAt).toBe(first.nextReviewAt);
  expect(wrong).toMatchObject({ attempts: 4, correct: 3, wrong: 1, streak: 0 });
  expect(scheduleTopicReview(topic, wrong, "reviewed", "normal", now)).toMatchObject({ attempts: 5, correct: 3, wrong: 1 });
  const yearEnd = scheduleTopicReview(topic, undefined, "reviewed", "normal", new Date(2026, 11, 31, 23));
  expect(yearEnd.nextReviewAt).toBe(new Date(2027, 0, 1, 23).toISOString());
});

test("revisa um material real, retoma em 360 px e abre o Tutor sem enviar", async ({ page }) => {
  test.setTimeout(90_000);
  const calls: Array<{ context?: { subject?: string }; chunks?: Array<{ metadata: { sourceName: string } }> }> = [];
  await page.route("**/api/tutor", async (route) => {
    calls.push(route.request().postDataJSON());
    await route.fulfill({ json: { text: "Vamos revisar os vetores.", provider: "gemini", model: "mock" } });
  });
  const studyId = await createRealStudy(page);
  await page.setViewportSize({ width: 360, height: 780 });
  await page.goto(`/estudo?tema=${studyId}`);
  await page.getByRole("link", { name: "Revisão por disciplina" }).click();
  await page.getByRole("button", { name: "Iniciar revisão" }).click();
  const before = await readIndexedDBStore(page, "studies");
  await expect(page.getByRole("link", { name: /fundamentos.txt/ })).toBeVisible();
  await page.getByRole("checkbox", { name: "Achei difícil" }).check();
  await page.getByRole("button", { name: "Revisei sem corrigir" }).click();
  await expect(page.getByText("Revisão registrada.")).toBeVisible();
  expect(await readIndexedDBStore(page, "studies")).toEqual(before);
  await page.goto("/");
  const progress = page.getByRole("region", { name: "Meu progresso" });
  await progress.getByRole("link", { name: "Estruturas de dados" }).and(page.locator('a[href^="/estudo/revisao?disciplina="]')).click();
  await expect(page).toHaveURL(/\/estudo\/revisao\?disciplina=/);
  await page.reload();
  await expect(page.getByText(/Revisões: 1.*0 acertos, 0 erros.*Dificuldade declarada/)).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(360);
  await page.getByRole("button", { name: "Iniciar revisão" }).click();
  await page.getByRole("button", { name: "Continuar no Tutor" }).click();
  await expect(page.getByLabel("Mensagem para o Tutor IA")).toHaveValue(/Estruturas de dados/);
  expect(calls).toHaveLength(0);
  await expect(page.getByText("Estudar matéria completa · Algoritmos")).toBeVisible();
  await page.getByRole("button", { name: "Enviar", exact: true }).click();
  await expect(page.getByRole("region", { name: "Conversa com o Tutor IA" }).getByText("Vamos revisar os vetores.")).toBeVisible();
  expect(calls[0]?.context?.subject).toBe("Algoritmos");
  expect(calls[0]?.chunks?.map((chunk) => chunk.metadata.sourceName)).toContain("fundamentos.txt");

  await page.setViewportSize({ width: 1280, height: 780 });
  await page.goto("/organizar");
  await page.getByRole("button", { name: "Ações para fundamentos.txt" }).click();
  await page.getByRole("menuitem", { name: "Mover" }).click();
  await page.getByRole("textbox", { name: "Matéria", exact: true }).fill("Outra disciplina");
  await expect(page.getByRole("dialog").getByRole("status")).toHaveText("Alterações salvas automaticamente");
  await page.getByRole("dialog").getByRole("button", { name: "Fechar" }).first().click();
  await page.goto("/estudo/revisao");
  const discipline = page.getByRole("combobox", { name: "Disciplina", exact: true });
  await discipline.selectOption({ label: "Outra disciplina · Ciência da Computação · 1º semestre" });
  await expect(page.getByText("Sem revisão registrada", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Iniciar revisão" }).click();
  await page.getByRole("button", { name: "Errei" }).click();
  await expect(page.getByText("Revisão registrada.")).toBeVisible();
  await discipline.selectOption({ label: "Algoritmos · Ciência da Computação · 1º semestre" });
  await expect(page.getByText(/Material indisponível.*Histórico preservado/)).toBeVisible();
  await page.goto("/organizar");
  await page.getByRole("button", { name: "Ações para fundamentos.txt" }).click();
  await page.getByRole("menuitem", { name: "Excluir" }).click();
  await expect(page.getByText("Material e dados derivados foram removidos.")).toBeVisible();
  await page.goto("/estudo/revisao");
  await discipline.selectOption({ label: "Outra disciplina · Ciência da Computação · 1º semestre" });
  await expect(page.getByText(/Material indisponível.*Histórico preservado/)).toBeVisible();
});
